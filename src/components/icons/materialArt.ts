export const MATERIAL_KINDS = Object.keys(ART)

/** 稀有度的顏色（style.css 的 --r-*） */
export function rarityColor(rarity: string | undefined): string {
  return `var(--r-${RARITY_ORDER.includes(rarity ?? '') ? rarity : 'common'})`
}

export function materialArtPath(kind: string | undefined, tier: number): string {
  const art = ART[kind ?? ''] ?? ART.metal!
  return pixelPath(art[materialStage(tier)]!)
}

export function materialDraw(m: Pick<MaterialDef, 'kind' | 'tier' | 'rarity'>): { path: string; color: string } {
  return { path: materialArtPath(m.kind, m.tier), color: rarityColor(m.rarity) }
}
