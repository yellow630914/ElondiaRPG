/** 每 4 級一個區間：1～4、5～8、9～12、13～16；17 級以上沿用最後一張圖，顏色另外一種 */
export const MONSTER_BAND_LEVELS = 4
const BAND_ART = 4

/** 區間的顏色：越後面越危險 */
export const MONSTER_BAND_COLOR = ['#b4b89c', '#d8c45a', '#e08a3c', '#d4553c', '#b65ad8']

export const MONSTER_BAND_NAME = ['1～4 級', '5～8 級', '9～12 級', '13～16 級', '17 級以上']

/** 等級所在的區間（0 起算） */
export function monsterBand(level: number): number {
  const n = Math.floor((Math.max(1, Math.round(level || 1)) - 1) / MONSTER_BAND_LEVELS)
  return Math.min(MONSTER_BAND_COLOR.length - 1, n)
}

