/** Markdown → 純文字：拿掉標題的 #、粗體、程式碼標記，表格改成「種類：檔案（筆數）」 */
function toText(md: string): string {
  return md
    .split('\n')
    .filter((l) => !/^\|---/.test(l))
    .map((l) => {
      if (/^\| 種類 \|/.test(l)) return ''
      const row = /^\| (.+?) \| `(.+?)` \| (\d+) \| (.+?) \|$/.exec(l)
      if (row) return `- ${row[1]}：${row[2]}（${row[3]} 筆）${row[4] !== '—' ? `　製作指南：${row[4]}` : ''}`
      const h = /^(#+) (.*)$/.exec(l)
      if (h) return h[1] === '#' ? `${h[2]}\n${'='.repeat(30)}` : `【${h[2]}】`
      return l.replace(/\*\*(.+?)\*\*/g, '$1').replace(/`([^`]+)`/g, '$1').replace(/<(https?:[^>]+)>/g, '$1')
    })
    .join('\n')
}
