def _outcome(node, key):
    if key in ('S', 'F'):
        return node.get('success' if key == 'S' else 'fail')
    for o in node.get('options', []):
        if o['label'] == key: return o.get('success')
    return None


def place_scenes(batch, romance4=()):
    by_id = {s['id']: s for s in batch}
    n = 0
    for sid, nodes in SCENES.items():
        s = by_id[sid]
        assert 'adult' in (s.get('tags') or []), sid
        for nid, outs in nodes.items():
            node = next(x for x in s['nodes'] if x['id'] == nid)
            labels = [o['label'] for o in node.get('options', [])]
            # 選擇的任務點：每個選項都要有場景
            if node['kind'] == 'choice': assert sorted(labels) == sorted(outs), (sid, nid)
            for key, (scene, add) in outs.items():
                o = _outcome(node, key)
                assert o is not None, (sid, nid, key)
                assert len(scene) <= 300, (sid, key, len(scene))
                o['scene'] = scene
                if add and add not in o.get('text', ''):
                    o['text'] = f"{o.get('text', '')}{add}"
                    assert len(o['text']) <= 400, (sid, key, len(o['text']))
                n += 1
    # 非成人向角色線的「四」：那一晚的每個選項，場景就是結果的文字
    for s in romance4:
        node = next(x for x in s['nodes'] if x['id'] == 'night')
        for o in node['options']:
            o['success']['scene'] = o['success']['text'][:300]
            n += 1
    return n
