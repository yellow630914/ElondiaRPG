def done(prefix, i, npc, title, text, at, requires, options, allies=None, **kw):
    """一、二的最後一步：options：[(label, text, affinity, memory, scene 或 None)]，都設 f'{prefix}_{i}_done' 並完成"""
    opts = []
    for l, t, a, m, sc in options:
        o = {'text': t, 'set_flags': [f'{prefix}_{i}_done'], 'effects': [aff(npc, a, '一起經歷了一段事')] + ([mem(m)] if m else []), 'complete': True}
        if sc:
            o['scene'] = sc
        opts.append({'label': l, 'success': o})
    if allies:
        kw['allies'] = allies
    return node('done', title, text, at, requires, 'choice', options=opts, **kw)


