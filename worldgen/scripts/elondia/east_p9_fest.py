def split_race(stories):
    """那達慕的第二個任務：不是人馬族的主角騎在冠軍背上（ride），人馬族的主角跟他並肩跑（run）；兩個版本設同一個旗標"""
    s = next(x for x in stories if x['id'] == 'tdnaadam_race')
    ride = s['nodes'][0]
    ride['requires'] = {**ride['requires'], 'pc_races_none': ['centaur']}
    run = {
        "id": "run", "title": "跟冠軍並肩跑回營帳", "kind": "check", "at": NAADAM, "hours": ride.get('hours'),
        "text": "賽馬的冠軍是一個年輕的人馬族，渾身是汗地奔到你身邊，用媞丹話笑著說：「彩頭也是匹好馬。比一比，輸的人這一路歸贏的人。」你們並肩往營帳跑，他一邊跑一邊伸手撈你的腰、拍你的馬臀。",
        "check": {"attr": "str", "dc": 15},
        "success": {"text": "你四蹄翻飛，一路領先他半個身子跑到營帳，他喘著氣認輸，說你是他見過跑得最快的彩頭。", "effects": [money(100)]},
        "fail": {"text": "你跑輸了半個身子。他從後面追上來，一把摟住你的人身，兩副馬身擠在一起，一邊慢慢走一邊把你摸了個遍。", "effects": [cond('aroused')],
                 "scene": "賽馬的冠軍從後面追上人馬族的主角，兩副馬身並排擠在一起，他摟住主角的人身揉捏主角的胸口，另一隻手往後撫過主角的馬背和馬臀，一路慢慢走回營帳。"},
        "requires": {**ride['requires'], 'pc_races': ['centaur']},
    }
    del run['requires']['pc_races_none']
    for k in ('success', 'fail'):
        run[k]['set_flags'] = list(ride[k]['set_flags'])
    if run['hours'] is None:
        del run['hours']
    s['nodes'].insert(1, run)


