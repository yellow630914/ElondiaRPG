# ---------------- 世界書：神祇信仰的其他信仰加上龍母祠 ----------------
LORE_ANCHOR = '大烨朝廷祭天、祭祖龙（化龙族对热量之龙的想像，不是神祇）；'
LORE_ADD = '民间把祖龙的配偶「龙母」当作送子的神，各地有小小的龙母祠，香头带着求子的女人走五座祠「借五方的龙种」，朝廷的祀典不承认（礼部称为淫祀）；瑔州港的水手把玉璘族的凤母当成「海里的龙母」；'


def write_lore():
    p = 'data/worldbook/elondia.worldbook.json'
    src = open(p, encoding='utf-8').read()
    if LORE_ADD in src:
        return
    assert src.count(LORE_ANCHOR) == 1
    src = src.replace(LORE_ANCHOR, LORE_ANCHOR + LORE_ADD)
    json.loads(src)
    open(p, 'w', encoding='utf-8').write(src)
    print('世界書：龍母祠')


