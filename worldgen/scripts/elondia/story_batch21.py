def route_nodes():
    """路線的選擇：條件沒有「或」，所以照兩邊的走向拆成互不重疊的六個任務點，玩家只會遇到符合的那一個"""
    def node(nid, cond, opts):
        req = {"flags": ["pol_echoed"], **cond}
        return {"id": nid, "title": "決定世界要往哪裡走", "text": ROUTE_TEXT,
                "at": at_cell("rivervale", "guild"), "requires": req, "kind": "choice", "options": opts}
    return [node("route_peace", PEACE, [PEACE_OPT]), node("route_war", WAR, [WAR_OPT])] + \
        [node("route_mixed_%d" % (i + 1), c, MIXED_OPTS) for i, c in enumerate(MIXED)]


