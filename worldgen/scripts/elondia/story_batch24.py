def aff(npc, d, why):
    return {"type": "affinity", "npc": npc, "delta": d, "reason": why}


def at_npc(npc):
    return {"where": "npc", "npc": npc}


def at_out(loc):
    return {"where": "outskirts", "location": loc}


def at_cell(loc, cell):
    return {"where": "cell", "location": loc, "cell": cell}


def pick(items, labels, texts, npc):
    return [{"label": lb, "success": {"text": tx, "effects": [reward(it), aff(npc, 5, '把作品交給你')], "complete": True}}
            for it, lb, tx in zip(items, labels, texts)]


def quest(sid, title, summary, rank, merit, npc, lv, req, start, nodes, money, xp, tags=None):
    pre = sid
    out = {"id": sid, "title": title, "summary": summary, "rank": rank, "merit": merit,
           "start": {"kind": "npc", "npc": npc, "min_level": lv, **({"requires": req} if req else {}), "text": start},
           "start_flags": [f"{pre}_start"], "nodes": [], "rewards": [{"type": "money", "amount": money}, {"type": "xp", "amount": xp}]}
    prev = f"{pre}_start"
    for i, n in enumerate(nodes):
        n = dict(n)
        n["requires"] = {"flags": [prev]}
        flag = f"{pre}_{n['id']}"
        if n['kind'] != 'choice':
            for k in ('success', 'fail'):
                if k in n: n[k] = {**n[k], "set_flags": [flag]}
        prev = flag
        out["nodes"].append(n)
    if tags: out["tags"] = tags
    return out


