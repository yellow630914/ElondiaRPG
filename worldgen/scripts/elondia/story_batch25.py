    who = f'par_mark_with{v or "_lucia"}'
    q1 = quest(
        s1, '小腹上的紋', T['s1_summary'], 'D', 5, npc, 1, {"flags_none": ["par_mark_help_start", "par_mark_help_cas_start"], **mark()}, T['s1_start'],
        [
            {"id": "read", "title": T['read_title'], "kind": "check", "at": at_npc(npc), "text": T['read_text'],
             "check": {"attr": T['read_attr'], "dc": 12},
             "success": {"text": T['read_ok']}, "fail": {"text": T['read_fail'], "effects": [cor(MARK, 5)]}},
            {"id": "ask", "title": T['ask_title'], "kind": "story", "at": at_cell('bloodplume', T['ask_cell']), "text": T['ask_text'],
             "success": {"text": T['ask_ok']}},
            {"id": "answer", "title": T['ans_title'], "kind": "choice", "at": at_npc(npc), "text": T['ans_text'],
             "options": [{"label": T['ans_label'], "success": {"text": T['ans_ok'], "set_flags": ["par_mark_1_done", who],
                                                              "effects": [cor(MARK, -5), aff(npc, 10, '把契紋的事交給她'), mem(T['ans_mem'])], "complete": True}}]},
        ], [money(100), {"type": "xp", "amount": 300}], tags)
    q2 = quest(
        s2, '契約的另一半', T['s2_summary'], 'C', 8, npc, 4, {"flags": ["par_mark_1_done", who], **mark(min=30)}, T['s2_start'],
        [
            {"id": "imps", "title": '在血羽城堡近郊擊退薇絲佩菈的僕從', "kind": "combat", "at": at_out('bloodplume'), "text": T['imps_text'],
             "enemies": [["honor_succubus", 1], ["brimstone_imp", 2]],
             "success": {"text": T['imps_ok']}, "fail": {"text": T['imps_fail'], "effects": [cor(MARK, 8)]}},
            {"id": "answer", "title": T['s2a_title'], "kind": "choice", "at": at_npc(npc), "text": T['s2a_text'],
             "options": [{"label": '「去找契約的原本」', "success": {"text": T['s2a_ok'], "set_flags": ["par_mark_2_done"],
                                                            "effects": [aff(npc, 10, '一起追查契紋'), mem(T['s2_mem'])], "complete": True}}]},
        ], [money(300), {"type": "xp", "amount": 800}], tags)
    q3 = quest(
        s3, '契約書庫', T['s3_summary'], 'B', 10, npc, 7, {"flags": ["par_mark_2_done", who], **mark()}, T['s3_start'],
        [
            {"id": "archive", "title": '在血岩深穴的中層解讀魔族的契約書庫', "kind": "check", "at": at_dg('bloodrock_cave', 'middle'), "text": T['arch_text'],
             "check": {"attr": "int", "dc": 15},
             "success": {"text": T['arch_ok']}, "fail": {"text": T['arch_fail'], "effects": [cor(MARK, 5)]}},
            {"id": "guards", "title": '在血岩深穴的深層搶下契約的原本', "kind": "combat", "at": at_dg('bloodrock_cave', 'deep'), "text": T['guard_text'],
             "enemies": [["bloodsworn_guard", 2]],
             "success": {"text": T['guard_ok']}, "fail": {"text": T['guard_fail'], "effects": [cor(MARK, 8)]}},
            {"id": "answer", "title": T['s3a_title'], "kind": "choice", "at": at_npc(npc), "text": T['s3a_text'],
             "options": [{"label": '「等它最深的時候，我們改寫它」', "success": {"text": T['s3a_ok'], "set_flags": ["par_mark_3_done"],
                                                                 "effects": [aff(npc, 10, '一起拿回了契約的原本'), mem(T['s3_mem'])], "complete": True}}]},
        ], [money(800), {"type": "xp", "amount": 1800}], tags)
    q4 = quest(
        s4, '改寫契約', T['s4_summary'], 'B', 15, npc, 9, {"flags": ["par_mark_3_done", who], **mark(min=60)}, T['s4_start'],
        [
            {"id": "ritual", "title": T['rit_title'], "kind": "check", "at": at_npc(npc), "text": T['rit_text'],
             "check": {"attr": "cha", "dc": 16},
             "success": {"text": T['rit_ok']}, "fail": {"text": T['rit_fail'], "effects": [cor(MARK, 10)]}},
            {"id": "choose", "title": '決定契約的結局', "kind": "choice", "at": at_npc(npc), "text": T['end_text'],
             "options": [
                 {"label": '「我是這份契約的主人。」', "success": {"text": T['tame_ok'], "complete": True,
                                                         "effects": [par(MARK, 'tame'), aff(npc, 20, '一起改寫了契約'), mem(T['tame_mem'], 3)]}},
                 {"label": '「把它撕掉。」', "success": {"text": T['tear_ok'], "complete": True,
                                                   "effects": [par(MARK, 'remove'), money(1500), aff(npc, 15, '陪你撕毀了契約'), mem(T['tear_mem'], 3)]}},
             ]},
        ], [money(1500), {"type": "xp", "amount": 3000}], tags)
    return [q1, q2, q3, q4]


