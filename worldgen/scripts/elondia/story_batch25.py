def aff(npc, d, why):
    return {"type": "affinity", "npc": npc, "delta": d, "reason": why}


def mem(text, imp=2):
    return {"type": "memory", "summary": text, "importance": imp}


def cor(pid, n):
    return {"type": "corruption", "parasite": pid, "delta": n}


def par(pid, op):
    return {"type": "parasite", "parasite": pid, "op": op}


def money(n):
    return {"type": "money", "amount": n}


def at_npc(npc):
    return {"where": "npc", "npc": npc}


def at_cell(loc, cell):
    return {"where": "cell", "location": loc, "cell": cell}


def at_out(loc):
    return {"where": "outskirts", "location": loc}


def at_dg(loc, layer):
    return {"where": "dungeon", "location": loc, "layer": layer}


def quest(sid, title, summary, rank, merit, npc, lv, req, start, nodes, rewards, tags, start_flags=None):
    """節點依序解鎖：每個節點完成時立旗標 <sid>_<節點 id>，下一個節點要這個旗標；選擇節點的選項自己寫結果"""
    out = {"id": sid, "title": title, "summary": summary, "tags": tags, "rank": rank, "merit": merit,
           "start": {"kind": "npc", "npc": npc, "min_level": lv, "requires": req, "text": start},
           "start_flags": [f"{sid}_start", *(start_flags or [])], "nodes": [], "rewards": rewards}
    prev = f"{sid}_start"
    for n in nodes:
        n = dict(n)
        n["requires"] = {"flags": [prev]}
        flag = f"{sid}_{n['id']}"
        if n['kind'] != 'choice':
            for k in ('success', 'fail'):
                if k in n: n[k] = {**n[k], "set_flags": [flag, *n[k].get("set_flags", [])]}
        prev = flag
        out["nodes"].append(n)
    return out


def lin(**r):
    return {"parasites": {LIN: {"tamed": False, **r}}}


