def aff(npc, d, why):
    return {"type": "affinity", "npc": npc, "delta": d, "reason": why}


def mem(text, imp=2):
    return {"type": "memory", "summary": text, "importance": imp}


def money(n):
    return {"type": "money", "amount": n}


def item(name):
    return {"type": "item", "name": name, "qty": 1}


def cond(c):
    return {"type": "condition", "target": "pc", "condition": c, "add": True}


def at_npc(npc):
    return {"where": "npc", "npc": npc}


def at_cell(loc, cell):
    return {"where": "cell", "location": loc, "cell": cell}


def at_out(loc):
    return {"where": "outskirts", "location": loc}


def out(text, *effects, scene=None):
    o = {"text": text}
    if scene: o["scene"] = scene
    if effects: o["effects"] = list(effects)
    return o


def opt(label, success, fail=None, check=None, tags=None):
    o = {"label": label}
    if tags: o["tags"] = tags
    if check: o["check"] = {"attr": check[0], "dc": check[1]}
    o["success"] = success
    if fail: o["fail"] = fail
    return o


def quest(sid, title, summary, rank, npc, lv, prev, start, nodes, pay, xp, tags, done):
    """依序解鎖的任務點；最後的選擇每個選項都完成任務並立 done 旗標"""
    out_ = {"id": sid, "title": title, "summary": summary, "tags": tags, "rank": rank, "merit": 5,
            "start": {"kind": "npc", "npc": npc, "min_level": lv, "pc_body": BODY, **({"requires": {"flags": [prev]}} if prev else {}), "text": start},
            "start_flags": [f"{sid}_start"], "nodes": [], "rewards": [money(pay), {"type": "xp", "amount": xp}]}
    flag = f"{sid}_start"
    for n in nodes:
        n = dict(n)
        n["requires"] = {"flags": [flag]}
        flag = f"{sid}_{n['id']}"
        if n['kind'] == 'choice':
            for o in n['options']:
                for k in ('success', 'fail'):
                    if k in o: o[k] = {**o[k], "set_flags": [done], "complete": True}
        else:
            for k in ('success', 'fail'):
                if k in n: n[k] = {**n[k], "set_flags": [flag]}
        out_["nodes"].append(n)
    return out_


